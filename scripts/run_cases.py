#!/usr/bin/env python3
"""Prepare isolated OPERA COMI cases and optionally launch a verified command.

Default mode only creates case folders, case-parameters.comi, run.comi and a
manifest. External execution is opt-in through --run and remains bounded by
max_workers (default 1).
"""

from __future__ import annotations

import argparse
import csv
import itertools
import json
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from comi_preflight import analyse_file


@dataclass
class Case:
    case_id: str
    parameters: dict[str, Any]
    directory: Path
    run_comi: Path
    preflight_errors: int
    preflight_warnings: int
    status: str = "prepared"
    return_code: int | None = None


def load_config(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        config = json.load(handle)
    required = ("source_dir", "entry_comi", "parameters")
    missing = [key for key in required if key not in config]
    if missing:
        raise ValueError(f"Missing config keys: {', '.join(missing)}")
    if not isinstance(config["parameters"], dict) or not config["parameters"]:
        raise ValueError("parameters must be a non-empty object of numeric value lists.")
    return config


def parameter_sets(parameters: dict[str, Any]) -> list[dict[str, Any]]:
    names = list(parameters)
    values: list[list[Any]] = []
    for name in names:
        raw_values = parameters[name]
        if not isinstance(raw_values, list) or not raw_values:
            raise ValueError(f"Parameter {name!r} must contain a non-empty list.")
        normalised = []
        for value in raw_values:
            if isinstance(value, bool):
                normalised.append(value)
            elif isinstance(value, (int, float)) and not isinstance(value, complex):
                normalised.append(value)
            else:
                raise ValueError(f"Parameter {name!r} has unsupported value {value!r}; use numeric/boolean values only.")
        values.append(normalised)
    return [dict(zip(names, combination, strict=True)) for combination in itertools.product(*values)]


def comi_name(name: str) -> str:
    return name if name.startswith("#") else f"#{name}"


def comi_value(value: Any) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    return format(float(value), ".15g")


def write_case_parameters(path: Path, case_id: str, parameters: dict[str, Any]) -> None:
    lines = [f"/ Generated by run_cases.py for {case_id}", f"$STRING CASE_ID '{case_id}'"]
    for name, value in parameters.items():
        lines.append(f"$CONSTANT {comi_name(name)} {comi_value(value)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def clear_generated_case(case_dir: Path, case_root: Path) -> None:
    """Remove only a case directory this tool has previously generated."""
    if case_dir.parent != case_root:
        raise ValueError(f"Refusing to clear a directory outside case_root: {case_dir}")
    metadata = case_dir / "case-metadata.json"
    run_comi = case_dir / "run.comi"
    if not metadata.is_file() or not run_comi.is_file():
        raise ValueError(
            f"Refusing to replace {case_dir}: it does not look like a case generated by run_cases.py."
        )
    shutil.rmtree(case_dir)


def prepare_case(config_path: Path, config: dict[str, Any], index: int, parameters: dict[str, Any], overwrite: bool) -> Case:
    root = config_path.parent.resolve()
    source_dir = (root / config["source_dir"]).resolve()
    entry_rel = Path(config["entry_comi"])
    if not source_dir.is_dir():
        raise ValueError(f"source_dir does not exist: {source_dir}")
    if not (source_dir / entry_rel).is_file():
        raise ValueError(f"entry_comi does not exist under source_dir: {entry_rel}")

    case_root = (root / config.get("case_root", "cases")).resolve()
    case_id = f"case-{index:04d}"
    case_dir = case_root / case_id
    if case_dir.exists():
        if not overwrite:
            raise FileExistsError(f"Case directory exists: {case_dir}. Use --overwrite-prepared only for generated cases.")
        clear_generated_case(case_dir, case_root)
    (case_dir / "logs").mkdir(parents=True)
    shutil.copytree(source_dir, case_dir / "source", dirs_exist_ok=False)

    params_file = case_dir / "case-parameters.comi"
    write_case_parameters(params_file, case_id, parameters)
    run_comi = case_dir / "run.comi"
    run_comi.write_text(
        "\n".join(
            (
                f"/ Generated entry point for {case_id}",
                "$COMINPUT case-parameters.comi",
                f"$COMINPUT source/{entry_rel.as_posix()}",
                "",
            )
        ),
        encoding="utf-8",
    )
    metadata = {
        "case_id": case_id,
        "parameters": parameters,
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source_dir": str(source_dir),
        "entry_comi": str(entry_rel),
        "run_comi": str(run_comi),
    }
    (case_dir / "case-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    allowed_variables = {comi_name(name).upper() for name in parameters}
    issues = analyse_file(run_comi, allowed_variables)
    # Check every copied source command file as well as the generated wrapper.
    # This catches missing includes and undefined variables hidden beneath entry_comi.
    for source_comi in sorted((case_dir / "source").rglob("*.comi")):
        issues.extend(analyse_file(source_comi, allowed_variables))
    errors = sum(issue.level == "error" for issue in issues)
    warnings = sum(issue.level == "warning" for issue in issues)
    (case_dir / "preflight.json").write_text(
        json.dumps([issue.__dict__ for issue in issues], indent=2) + "\n", encoding="utf-8"
    )
    return Case(case_id, parameters, case_dir, run_comi, errors, warnings, "prepared" if not errors else "preflight_failed")


def run_case(case: Case, command_template: list[str]) -> Case:
    if case.preflight_errors:
        case.status = "not_run_preflight_failed"
        return case
    values = {
        "case_dir": str(case.directory),
        "run_comi": str(case.run_comi),
        "source_dir": str(case.directory / "source"),
        "case_id": case.case_id,
    }
    command = [item.format(**values) for item in command_template]
    stdout = case.directory / "logs" / "launcher.stdout.log"
    stderr = case.directory / "logs" / "launcher.stderr.log"
    try:
        with stdout.open("w", encoding="utf-8") as out, stderr.open("w", encoding="utf-8") as err:
            completed = subprocess.run(command, cwd=case.directory, stdout=out, stderr=err, check=False)
        case.return_code = completed.returncode
        case.status = "completed" if completed.returncode == 0 else "launcher_failed"
    except OSError as error:
        stderr.write_text(f"Failed to start command: {error}\n", encoding="utf-8")
        case.status = "launcher_start_failed"
    return case


def write_manifest(path: Path, cases: list[Case], mode: str) -> None:
    fieldnames = ["case_id", "status", "return_code", "case_dir", "run_comi", "preflight_errors", "preflight_warnings", "parameters"]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for case in cases:
            writer.writerow(
                {
                    "case_id": case.case_id,
                    "status": case.status,
                    "return_code": "" if case.return_code is None else case.return_code,
                    "case_dir": str(case.directory),
                    "run_comi": str(case.run_comi),
                    "preflight_errors": case.preflight_errors,
                    "preflight_warnings": case.preflight_warnings,
                    "parameters": json.dumps(case.parameters, ensure_ascii=False, sort_keys=True),
                }
            )
    manifest = {"mode": mode, "generated_utc": datetime.now(timezone.utc).isoformat(), "cases": [case.__dict__ | {"directory": str(case.directory), "run_comi": str(case.run_comi)} for case in cases]}
    path.with_suffix(".json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Prepare isolated OPERA COMI parameter-study cases.")
    parser.add_argument("config", type=Path, help="Path to sweep JSON configuration")
    parser.add_argument("--run", action="store_true", help="Actually launch the configured external command")
    parser.add_argument("--max-workers", type=int, default=None, help="Bounded external launcher concurrency")
    parser.add_argument("--overwrite-prepared", action="store_true", help="Replace existing generated case folders")
    args = parser.parse_args()
    config_path = args.config.expanduser().resolve()
    config = load_config(config_path)
    combinations = parameter_sets(config["parameters"])
    max_workers = args.max_workers if args.max_workers is not None else int(config.get("max_workers", 1))
    if max_workers < 1:
        parser.error("max-workers must be at least 1")
    if args.run and (not isinstance(config.get("command"), list) or not config.get("command")):
        parser.error("--run requires a non-empty command array in the configuration.")

    cases: list[Case] = []
    try:
        for index, parameters in enumerate(combinations, start=1):
            cases.append(prepare_case(config_path, config, index, parameters, args.overwrite_prepared))
    except (ValueError, FileExistsError, OSError) as error:
        print(f"Preparation failed: {error}", file=sys.stderr)
        return 2

    mode = "prepared"
    if args.run:
        mode = "run"
        command = config["command"]
        with ThreadPoolExecutor(max_workers=max_workers) as pool:
            futures = {pool.submit(run_case, case, command): case for case in cases}
            for future in as_completed(futures):
                completed = future.result()
                print(f"{completed.case_id}: {completed.status}")
    else:
        for case in cases:
            print(f"{case.case_id}: {case.status} ({case.directory})")

    manifest_path = (config_path.parent / config.get("manifest", "cases/manifest.csv")).resolve()
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    write_manifest(manifest_path, cases, mode)
    failures = [case for case in cases if case.status not in {"prepared", "completed"}]
    print(f"Wrote manifest: {manifest_path}")
    return 2 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
